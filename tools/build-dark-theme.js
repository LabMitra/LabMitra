// Builds the dark theme from assets/style.css.
// Run after changing colors in style.css:   node tools/build-dark-theme.js
// It reads every rule above the "DARK THEME" marker, works out a dark version of each colour
// (light backgrounds become dark, dark text becomes light, brand buttons stay as they are)
// and rewrites the block between the markers. Hand-made dark tweaks go in the "DARK THEME: manual" block.
const fs=require("fs"),path=require("path");
const file=path.join(__dirname,"..","assets","style.css");
const START="/* ===== DARK THEME (generated by tools/build-dark-theme.js, do not edit by hand) ===== */";
const END="/* ===== END DARK THEME (generated) ===== */";
let css=fs.readFileSync(file,"utf8");
const cut=css.indexOf(START);const base=cut<0?css:css.slice(0,cut);
const after=cut<0?"":css.slice(css.indexOf(END)+END.length);

// --- colour maths (sRGB <-> OKLCH) ---
const toLin=c=>(c/=255)<=.04045?c/12.92:((c+.055)/1.055)**2.4,toS=c=>Math.round(255*Math.min(1,Math.max(0,c<=.0031308?12.92*c:1.055*c**(1/2.4)-.055)));
function hex2lch(h){h=h.slice(1);if(h.length<=4)h=[...h].map(x=>x+x).join("");
  const[r,g,b]=[0,2,4].map(i=>toLin(parseInt(h.slice(i,i+2),16))),a=h.length===8?parseInt(h.slice(6),16)/255:1;
  const l=Math.cbrt(.4122214708*r+.5363325363*g+.0514459929*b),m=Math.cbrt(.2119034982*r+.6806995451*g+.1073969566*b),s=Math.cbrt(.0883024619*r+.2817188376*g+.6299787005*b);
  const L=.2104542553*l+.793617785*m-.0040720468*s,A=1.9779984951*l-2.428592205*m+.4505937099*s,B=.0259040371*l+.7827717662*m-.808675766*s;
  return{L,C:Math.hypot(A,B),h:Math.atan2(B,A),a}}
function lch2hex({L,C,h,a}){const A=C*Math.cos(h),B=C*Math.sin(h);
  const l=(L+.3963377774*A+.2158037573*B)**3,m=(L-.1055613458*A-.0638541728*B)**3,s=(L-.0894841775*A-1.291485548*B)**3;
  const r=toS(4.0767416621*l-3.3077115913*m+.2309699292*s),g=toS(-1.2684380046*l+2.6097574011*m-.3413193965*s),b=toS(-.0041960863*l-.7034186147*m+1.707614701*s);
  return"#"+[r,g,b].map(x=>x.toString(16).padStart(2,"0")).join("")+(a<1?Math.round(a*255).toString(16).padStart(2,"0"):"")}
const NAVY_H=hex2lch("#123b69").h;
// Light surface -> dark surface (keeps a hint of its hue)
const surface=c=>c.L<.8||c.a<.6?null:{L:.235+(1-c.L)*.7,C:c.C<.012?.022:Math.min(.07,c.C*1.3),h:c.C<.012?NAVY_H:c.h,a:c.a};
// Dark/mid text -> light text
const text=c=>c.L>=.66?null:{L:Math.min(.95,.93-(c.L-.2)*.45),C:Math.min(c.C,.13),h:c.h,a:c.a};
// Light border -> subtle dark border
const border=c=>c.L<.78||c.a<.6?null:{L:.33+(1-c.L)*.4,C:Math.min(.04,c.C+.015),h:c.C<.012?NAVY_H:c.h,a:c.a};
// Coloured shadows -> black shadows (a bit stronger so they still show)
const shadow=c=>c.L>.7?null:{L:0,C:0,h:0,a:Math.min(.6,c.a*2.2)};
const VARS={"--navy":"#123b69","--blue":"#1d70b7","--ink":"#182b43","--muted":"#64778d","--line":"#e2eaf2","--bg":"#f5f8fc","--green":"#13834e","--soft":"#eaf3fb"};
const KIND=p=>/^(color|fill|stroke|caret-color|text-decoration-color|-webkit-text-fill-color)$/.test(p)?text
  :/^(background|background-color|background-image)$/.test(p)?surface:/^(border|border-(top|right|bottom|left)(-color)?|border-color|outline|outline-color)$/.test(p)?border
  :/^(box-shadow|text-shadow|filter)$/.test(p)?shadow:null;
function convertValue(prop,val){const f=KIND(prop);if(!f)return null;let changed=false;
  // var(--x) used as a TEXT colour must be lightened; as a background, only light vars change (handled in :root)
  let v=val.replace(/var\((--[\w-]+)\)/g,(m,n)=>{if(f!==text||!VARS[n]||["--ink","--muted"].includes(n))return m;const r=f(hex2lch(VARS[n]));if(!r)return m;changed=true;return lch2hex(r)});
  v=v.replace(/#[0-9a-fA-F]{3,8}\b|\bwhite\b/g,m=>{if(m==="white"){if(f===text)return m;m="#ffffff"}
    if(![4,5,7,9].includes(m.length))return m;const r=f(hex2lch(m));if(!r)return m;changed=true;return lch2hex(r)});
  return changed?v:null}

// --- tiny CSS walker: handles nested @media, skips @keyframes/@font-face ---
const out=[];
function walk(src,wrap){let i=0;
  while(i<src.length){const open=src.indexOf("{",i);if(open<0)break;let sel=src.slice(i,open).replace(/\/\*[\s\S]*?\*\//g,"").trim();
    let depth=1,j=open+1;while(j<src.length&&depth){if(src[j]==="{")depth++;else if(src[j]==="}")depth--;j++}
    const body=src.slice(open+1,j-1);i=j;
    if(sel.startsWith("@media")){if(/print/.test(sel))continue;walk(body,sel);continue}
    if(sel.startsWith("@"))continue;
    if(!sel||/^:root$/.test(sel))continue;
    const decls=[];body.split(";").forEach(d=>{const k=d.indexOf(":");if(k<0)return;const p=d.slice(0,k).trim().toLowerCase(),v=d.slice(k+1).trim();if(/^background/.test(p)&&(/background-clip:\s*text/.test(body)||/wordmark/.test(sel)))return;const nv=convertValue(p,v);if(nv)decls.push(`${p}:${nv}`)});
    if(!decls.length)continue;
    const sels=sel.split(/,(?![^(]*\))/).map(s=>s.trim()).map(s=>/^(html|:root)\b/.test(s)?s.replace(/^(html|:root)/,"html[data-theme=dark]"):`html[data-theme=dark] ${s}`).join(",");
    const rule=`${sels}{${decls.join(";")}}`;out.push(wrap?`${wrap}{${rule}}`:rule)}}
walk(base,null);
const root=`html[data-theme=dark]{color-scheme:dark;--ink:#e3ebf5;--muted:#9fb0c4;--line:#2a3b52;--bg:#0b1320;--soft:#1c2b40}`;
const block=`${START}\n${root}\n${out.join("\n")}\n${END}`;
fs.writeFileSync(file,base.trimEnd()+"\n"+block+(after.trim()?after:"\n"));
console.log(`Dark theme: ${out.length} rules written.`);
