-- =====================================================================================
-- LabMitra v2: multiple labs.  Run once in Supabase > SQL Editor.  Safe to re-run.
-- =====================================================================================
-- What it does:
--   1. labs       : the 7 partner labs. BYOS is the "Recommended" (default) lab.
--   2. lab_tests  : each lab's own price list. Price shown = lab's website price - Rs 1 (e.g. 400 -> 399).
--   3. tests      : stays the master list patients see (one "CBC", whichever labs offer it).
--   4. bookings   : remember which lab processes each booking (one lab per booking).
--   5. place_booking : now takes the chosen lab and charges THAT lab's prices (checked on the server).
--   6. Imports Hypatho Lab's 598 tests (from the BYOS Lab Test Portfolio PDF).
-- Labs with no price list yet (BYOS, Lupin, Agilus, Thyrocare, Metropolis, Manipal) show as "Coming soon"
-- until their tests are added in Admin > Labs.

-- ---------- 1. tables ----------
create table if not exists labs(
  id serial primary key, name text not null unique, recommended boolean not null default false,
  sort int not null default 100, active boolean not null default true, created_at timestamptz default now());
create table if not exists lab_tests(
  id serial primary key,
  lab_id int not null references labs on delete cascade,
  test_id int not null references tests on delete cascade,
  lab_code text, lab_name text,            -- the lab's own code (Sr. No.) and name for this test
  website_price int,                       -- price on the lab's own website
  price int not null check (price>=0),     -- LabMitra price (website price - 1)
  turnaround text, tat_minutes int,
  active boolean not null default true, updated_at timestamptz default now(),
  unique(lab_id,test_id));
create unique index if not exists lab_tests_code_key on lab_tests(lab_id,lab_code);
alter table tests add column if not exists trending boolean not null default false;   -- shown on the home page
alter table tests add column if not exists import_key text;                            -- e.g. hypatho:196, for safe re-imports
create unique index if not exists tests_import_key on tests(import_key);
alter table bookings add column if not exists lab_id int references labs;
alter table bookings add column if not exists lab_name text;

-- ---------- 2. security ----------
alter table labs enable row level security; alter table lab_tests enable row level security;
drop policy if exists labs_sel on labs;      create policy labs_sel on labs for select using (true);
drop policy if exists labs_all on labs;      create policy labs_all on labs for all using (has_role(array['admin'])) with check (has_role(array['admin']));
drop policy if exists lt_sel on lab_tests;   create policy lt_sel on lab_tests for select using (active or has_role(array['admin']));
drop policy if exists lt_all on lab_tests;   create policy lt_all on lab_tests for all using (has_role(array['admin'])) with check (has_role(array['admin']));

